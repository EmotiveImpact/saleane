/** Columns about where or by whom something was sold, money it was paid with, or renewals. */
const NEVER =
  /^(location|branch|business|site|venue|sold by|staff|team member|employee|created by|modified|updated|payment (method|type)|tax|vat|auto.?renew|renewal|next payment|charge frequency|reward|points|shared|failed|cancel|opening|collections|net change|activity)|credit ?card|saved card|card (on file|type|brand|expir)/i

function leftOut(heading: string, kind: ValueKind) {
  const words = heading.replace(/([a-z])([A-Z])/g, '$1 $2')
  if (/credit ?card|saved card|card (on file|type|brand|expir)/i.test(words))
    return 'Card details never move across. Clients save their card again through a link.'
  if (/location|branch|business|site|venue/i.test(words))
    return 'Everything carried over belongs to your main location.'
  if (/sold by|staff|team member|employee|created by|modified|updated/i.test(words))
    return 'Who sold it or changed it is not needed.'
  if (/renew|next payment|frequency/i.test(words))
    return 'Renewals start again once clients save their card.'
  if (/point|reward/i.test(words)) return 'Loyalty points are not brought across.'
  if (/payment|method|tax|vat/i.test(words)) return 'How it was paid for is not needed.'
  if (/\bid\b|reference|ref\.?$|number$/i.test(words))
    return 'The old system’s own reference. Not needed.'
  if (kind === 'money') return 'Only what is left, and what it was bought for, come across.'
  return 'SALEANE has no place for this yet.'
}

